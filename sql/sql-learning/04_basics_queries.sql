---Lets see what we can do with (WHERE and HAVING) function

--WHERE =its used as a condition on raw data
---HAVING =its use on summarised group by data

--Lets we wants to see the results for specefic year, in this situation we use WHERE function. 

SELECT P.P_TYPE AS PRODUCT_TYPE, sum(L.L_QUANTITY) AS TOTAL_ITEMS_SOLD
FROM LINEITEM AS L
JOIN PART AS P ON L.L_PARTKEY=P.P_PARTKEY
WHERE year(L_RECEIPTDATE)>1995
GROUP BY P_TYPE
ORDER BY TOTAL_ITEMS_SOLD DESC
LIMIT 10;
---query order of execution: join>filter>select>aggrigate>groupby>orderby

---now we want to filter on our summarized table. lets we want to see those are >= 464118 as our top selling items. in this situation we will use HAVING function after GROUP BY.

SELECT P.P_TYPE AS PRODUCT_TYPE, sum(L.L_QUANTITY) AS TOTAL_ITEMS_SOLD
FROM LINEITEM AS L
JOIN PART AS P ON L.L_PARTKEY=P.P_PARTKEY
WHERE year(L_RECEIPTDATE)>1995
GROUP BY P_TYPE
HAVING TOTAL_ITEMS_SOLD >= 464118
ORDER BY TOTAL_ITEMS_SOLD DESC;


