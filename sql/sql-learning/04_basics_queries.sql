---Lets we are assigned to reports the total sales by Weekend and Weekdays.

SELECT * FROM ORDERS LIMIT 5;


WITH cte1 AS
(SELECT dayname(O_ORDERDATE) AS DAYNAMES, ROUND(SUM(O_TOTALPRICE),0) AS DAYWISE_TOTAL_SALES
FROM ORDERS
GROUP BY 1
ORDER BY 2 DESC)

SELECT 
CASE WHEN DAYNAMES IN ('Sat', 'Sun') THEN 'WEEKEND' ELSE 'WEEKDAYS' END AS DAY_TYPE, SUM(DAYWISE_TOTAL_SALES) AS WEEKEND_WEEKDAY_SALES
FROM cte1
GROUP BY DAY_TYPE
ORDER BY 2 DESC;
---anoter way
