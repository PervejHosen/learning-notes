---what are the top 10 sold products by total quantity(L_QUANTITY) and total order value(L_EXTENDERPRICE*L_DISCOUNT*L_TAX)

SELECT L_PARTKEY, sum(L_QUANTITY) AS TOTAL_ITEMS_SOLD 
FROM LINEITEM
GROUP BY L_PARTKEY
ORDER BY TOTAL_ITEMS_SOLD DESC LIMIT 10;

SELECT L_PARTKEY, sum(L_EXTENDEDPRICE*L_DISCOUNT*L_TAX) AS TOTAL_ORDER_VALUE
FROM LINEITEM
GROUP BY 1
ORDER BY 2 DESC
LIMIT 10;

---lets join the table to see the name of the top 10 profucts ype

SELECT P.P_TYPE AS PRODUCT_TYPE, sum(L.L_QUANTITY) AS TOTAL_ITEMS_SOLD
FROM LINEITEM AS L
JOIN PART AS P ON L.L_PARTKEY=P.P_PARTKEY 
GROUP BY P_TYPE
ORDER BY TOTAL_ITEMS_SOLD DESC
LIMIT 10;

