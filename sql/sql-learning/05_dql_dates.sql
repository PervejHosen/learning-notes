---To see the date range from a date column
SELECT MAX(O_ORDERDATE) AS MOST_RECENT_DATE,MIN(O_ORDERDATE) AS EARLIEST_RECENT_DATE 
FROM ORDERS; ---1998-08-02, 1992-01-01

---to see only the range of years.
SELECT 
date_part(year, MAX(O_ORDERDATE)) AS MOST_RECENT_DATE,
date_part(year,MIN(O_ORDERDATE)) AS EARLIEST_RECENT_DATE 
FROM ORDERS;

---lets find out the Total order value by year wise.
SELECT date_part(year,O_ORDERDATE), round(sum(o_totalprice),0) as TOTAL_YEARLY_ORDER_VALUE
FROM ORDERS
GROUP BY 1
ORDER BY 1;

---now we want to see year & month wise Total ordered values
SELECT DATE_PART(YEAR, O_ORDERDATE) AS ORDERS_YEARS, EXTRACT(MONTH FROM O_ORDERDATE) AS ORDER_MONTHS, ROUND(SUM(O_TOTALPRICE),0) AS TOTAL_ORDER_VALUE
FROM ORDERS
GROUP BY 1, 2
ORDER BY 1, 2;

------FIVE NUMBER SUMMARY
SELECT 
min(O_TOTALPRICE) AS MIN_ORDER_VALUE,
PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY O_TOTALPRICE) AS Q1,
PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY O_TOTALPRICE) AS MEDIAN,
PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY O_TOTALPRICE) AS Q3,
max(O_TOTALPRICE) AS MAX_ORDER_VALUE
FROM ORDERS;

--FINDING OUTLIERS USING FIVE NUMBER SUMMARY AND INTER-QUARTILE RANGES (IQR)
WITH FIVE_NUMBER_SUMMARY AS
(SELECT 
min(O_TOTALPRICE) AS MIN_ORDER_VALUE,
PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY O_TOTALPRICE) AS Q1,
PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY O_TOTALPRICE) AS MEDIAN,
PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY O_TOTALPRICE) AS Q3,
max(O_TOTALPRICE) AS MAX_ORDER_VALUE,
(PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY O_TOTALPRICE)-PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY O_TOTALPRICE)) AS IQR
FROM ORDERS)

SELECT (Q1-1.5*IQR) AS LOWER_HINGE, (Q3+1.5*IQR) AS UPPER_HINGE
FROM FIVE_NUMBER_SUMMARY AS F; --UPPER HINGE: 421,908.44125

--REMOVING OUTLIERS
WITH FIVE_NUMBER_SUMMARY AS
(SELECT 
MIN(O_TOTALPRICE) AS MIN_ORDER_VALUE,
PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY O_TOTALPRICE) AS Q1,
PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY O_TOTALPRICE) AS MEDIAN,
PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY O_TOTALPRICE) AS Q3,
MAX(O_TOTALPRICE) AS MAX_ORDER_VALUE,
(PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY O_TOTALPRICE)-PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY O_TOTALPRICE)) AS IQR
FROM ORDERS),
HINGES AS
(SELECT (Q1-1.5*IQR) AS LOWER_HINGE, (Q3+1.5*IQR) AS UPPER_HINGE
FROM FIVE_NUMBER_SUMMARY AS F)


SELECT O_TOTALPRICE FROM ORDERS
WHERE O_TOTALPRICE > (SELECT LOWER_HINGE FROM HINGES) AND O_TOTALPRICE < (SELECT UPPER_HINGE FROM HINGES);
